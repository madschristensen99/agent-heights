/** All unique category tags across the catalog. */
export const MCP_CATEGORIES: string[] = [...new Set(MCP_CATALOG.flatMap((s) => s.category))].sort();

/** Search the catalog by text query. */
export function searchCatalog(query: string): MCPCatalogServer[] {
  const q = query.toLowerCase().trim();
  if (!q) return MCP_CATALOG;
  return MCP_CATALOG.filter((s) =>
    s.name.toLowerCase().includes(q) ||
    s.summary.toLowerCase().includes(q) ||
    s.description.toLowerCase().includes(q) ||
    s.category.some((c) => c.toLowerCase().includes(q)),
  );
}

/** Filter the catalog by category. */
export function filterByCategory(category: string): MCPCatalogServer[] {
  return MCP_CATALOG.filter((s) => s.category.includes(category));
}

/** Get a server by ID. */
export function getServerById(id: string): MCPCatalogServer | undefined {
  return MCP_CATALOG.find((s) => s.id === id);
}

/** Get a server by its remote URL. Used to look up icon/branding for agents
 *  whose MCPServerConfig was persisted before the `icon` field was added. */
export function getServerByUrl(url: string): MCPCatalogServer | undefined {
  return MCP_CATALOG.find((s) => s.url === url);
}

/**
 * Build a compact categorized summary of the curated MCP catalog.
 * Used to inject knowledge into Agent Resources's context so she can recommend
 * MCP servers to users without browsing the marketplace.
 */
export function catalogSummary(): string {
  const byCategory: Record<string, { name: string; summary: string; auth: string }[]> = {};
  for (const s of MCP_CATALOG) {
    const entry = { name: s.name, summary: s.summary, auth: s.authType };
    for (const cat of s.category) {
      if (!byCategory[cat]) byCategory[cat] = [];
      if (!byCategory[cat].some((e) => e.name === s.name)) {
        byCategory[cat].push(entry);
      }
    }
  }
  const lines: string[] = [];
  for (const cat of Object.keys(byCategory).sort()) {
    const items = byCategory[cat];
    lines.push(`  ${cat}:`);
    for (const item of items) {
      const authTag = item.auth === "open" ? " (no auth)" : item.auth === "oauth" ? " (OAuth)" : " (API key)";
      lines.push(`    - ${item.name}${authTag}: ${item.summary}`);
    }
  }
  return lines.join("\n");
}

